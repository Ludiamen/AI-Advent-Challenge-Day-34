"""Метрики ассистента файлов — без текстов (День 34, FR-10, plan D-09).

На задачу — строка: время, круги, вызовы по инструментам, прочитано и изменено файлов, находки
(подтверждено / нет), токены, стоимость, итог (правки / отчёт / ошибка) и решение человека
отдельным событием. Цели, тексты файлов и находок сюда не попадают.
"""

from __future__ import annotations

import json
import os
import threading
import time
from typing import Any, Iterable

from agent.devassist.metrics import перцентиль

ПОЛЯ = ("время", "событие", "задача", "канал", "модель", "итог", "статус", "кругов", "вызовов", "по_инструментам",
        "прочитано", "изменено", "находок", "подтверждено", "токены_вход", "токены_выход", "стоимость", "секунд",
        "применяется", "решение", "ошибка")
_замок = threading.Lock()


def записать(строка: dict[str, Any], путь: str) -> dict[str, Any]:
    чисто = {к: строка[к] for к in ПОЛЯ if к in строка}
    чисто.setdefault("время", time.strftime("%Y-%m-%dT%H:%M:%S"))
    if isinstance(чисто.get("ошибка"), str):
        чисто["ошибка"] = чисто["ошибка"][:120]
    os.makedirs(os.path.dirname(путь), exist_ok=True)
    with _замок, open(путь, "a", encoding="utf-8") as f:
        f.write(json.dumps(чисто, ensure_ascii=False) + "\n")
    return чисто


def прочитать(путь: str) -> list[dict[str, Any]]:
    try:
        with open(путь, encoding="utf-8") as f:
            return [json.loads(с) for с in f if с.strip()]
    except (OSError, json.JSONDecodeError):
        return []


def из_задачи(з: Any, канал: str = "") -> dict[str, Any]:
    по: dict[str, int] = {}
    for в in з.вызовы:
        по[в["имя"]] = по.get(в["имя"], 0) + 1
    итог = "ошибка" if з.статус == "не выполнено" else "правки" if з.diff else "отчёт"
    return {"событие": "задача", "задача": з.id, "канал": канал, "модель": з.модель, "итог": итог,
            "статус": з.статус, "кругов": з.круги, "вызовов": len(з.вызовы), "по_инструментам": по,
            "прочитано": len(з.прочитаны), "изменено": len(з.изменены), "находок": len(з.находки),
            "подтверждено": sum(1 for н in з.находки if н.get("подтверждена")),
            "токены_вход": з.токены_вход, "токены_выход": з.токены_выход, "стоимость": round(з.стоимость, 5),
            "секунд": round(з.секунд, 1), "применяется": bool(з.проверка.get("применяется")),
            "ошибка": з.итог if з.статус == "не выполнено" else ""}


def сводка(строки: Iterable[dict[str, Any]]) -> dict[str, Any]:
    строки = list(строки)
    задачи = [с for с in строки if с.get("событие") == "задача"]
    решения = [с for с in строки if с.get("событие") == "решение"]
    секунды = [float(с.get("секунд", 0)) for с in задачи]
    n = len(задачи) or 1
    итоги: dict[str, int] = {}
    for с in задачи:
        итоги[с.get("итог", "?")] = итоги.get(с.get("итог", "?"), 0) + 1
    return {"задач": len(задачи), "итоги": итоги,
            "p50_с": round(перцентиль(секунды, 0.5), 1) if секунды else 0,
            "p95_с": round(перцентиль(секунды, 0.95), 1) if секунды else 0,
            "кругов_в_среднем": round(sum(с.get("кругов", 0) for с in задачи) / n, 1),
            "прочитано_в_среднем": round(sum(с.get("прочитано", 0) for с in задачи) / n, 1),
            "стоимость": round(sum(с.get("стоимость", 0) for с in задачи), 4),
            "стоимость_на_задачу": round(sum(с.get("стоимость", 0) for с in задачи) / n, 5),
            "применено": sum(1 for с in решения if с.get("решение") == "применить"),
            "отклонено": sum(1 for с in решения if с.get("решение") == "отклонить")}
