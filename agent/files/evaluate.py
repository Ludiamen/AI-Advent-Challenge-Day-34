"""Контрольный набор ассистента файлов: эталон кодом + судья ds-pro (День 34, plan D-10, SC-02…SC-07).

Каждая цель — новая задача на своей базе (коммит проекта или ветка посеянных случаев);
проверки кодом по виду цели, затем судья: выполнена ли цель по сути. Повторный прогон
сравнивается с первым: затронутые файлы (изменённые и файлы подтверждённых находок).
"""

from __future__ import annotations

import fnmatch
import json
import os
from typing import Any

ФАЙЛ = "files-goals.json"
СЛУЧАИ = "files-cases.json"
СУДЬЯ = "ds-pro"
ПРАВИЛА_КОДА = ("стек-бэкенд", "бд", "секреты-вне-кода", "секреты-в-url", "sql-только-параметры")

ПРОМПТ_СУДЬИ = """\
Ты проверяешь работу ассистента разработчика с файлами проекта. Цель, которую ему дали: «{цель}».
Итог ассистента: «{итог}»
Подтверждённые кодом находки (файл:строка «настоящая строка файла» — суть): {находки}
Черновик правок (diff, может быть пуст):
{diff}
«false» — только при существенном: цель не выполнена в главном; правка ошибочна или портит файл;
итог противоречит находкам или содержит явную выдумку. Неполнота в мелочах, стиль, выбор места
файла по соглашениям — не причина для false (назови это в «почему»). Кода проекта ты не видишь,
кроме строк находок: не оценивай факты о коде, которых нет в находках и diff. Находки — выборка
мест (по одной-две на файл): число мест и файлов в итоге может быть больше числа находок.
Ответь только JSON: {{"верно": true|false, "почему": "одна фраза"}}.
"""


def _корень() -> str:
    return os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def загрузить(путь: str = "") -> dict[str, Any]:
    with open(путь or os.path.join(_корень(), ФАЙЛ), encoding="utf-8") as f:
        return json.load(f)


def случаи(путь: str = "") -> dict[str, Any]:
    with open(путь or os.path.join(_корень(), СЛУЧАИ), encoding="utf-8") as f:
        return json.load(f)


def эталон_использований(копия: Any, база: str, имя: str) -> set[str]:
    вывод = копия.git("grep", "-l", "-w", "-I", "-F", "-e", имя, база, "--")
    return {с.split(":", 1)[1] for с in вывод.splitlines() if ":" in с}


def затронуты(з: Any, проверки: dict[str, Any] | None = None) -> set[str]:
    """Что сравнивать между прогонами (SC-07): изменённые файлы; у отчётов без правок — места из
    эталона (файлы с именем, посеянные нарушения), а не справочные файлы находок."""
    if з.изменены:
        return set(з.изменены)
    return set((проверки or {}).get("ключевые") or [])


def проверить(цель: dict[str, Any], з: Any, копия: Any, все_случаи: dict[str, Any]) -> dict[str, Any]:
    п: dict[str, Any] = {"выполнена": з.статус in ("готово", "ждёт подтверждения")}
    подтв = [н for н in з.находки if н.get("подтверждена")]
    п["прочитано ≥ 2"] = len(з.прочитаны) >= 2
    вид = цель["вид"]
    # SC-02: в «использованиях» выдуманных мест 0; в остальных видах непроверенное помечается (FR-04),
    # а подтверждённых — не меньше 80 %.
    эталон: set[str] = set()
    if вид == "использования":
        # Выдуманное место — неподтверждённая находка в файле, где имени нет; неточная цитата в файле
        # из эталона — не выдумка (показывается отдельно).
        эталон = эталон_использований(копия, з.база, цель["имя"])
        п["выдуманных мест нет"] = all(н.get("подтверждена") or н.get("файл") in эталон for н in з.находки)
        п["неточных цитат"] = sum(1 for н in з.находки if not н.get("подтверждена"))
    elif з.находки:
        доля = len(подтв) / len(з.находки)
        п["подтверждено находок"] = f"{len(подтв)} из {len(з.находки)}"
        п["подтверждено ≥ 80 %"] = доля >= 0.8
    if вид == "использования":
        найдено = {н["файл"] for н in подтв} & эталон
        п["полнота"] = round(len(найдено) / len(эталон), 2) if эталон else 1.0
        п["полнота ≥ 90 %"] = п["полнота"] >= 0.9
        п["пропущены"] = sorted(эталон - найдено)
        п["ключевые"] = sorted(найдено)
    if вид == "документация":
        п["меняет нужный документ"] = all(ф in з.изменены for ф in цель["файлы"])
        п["в черновике есть нужное"] = all(с in з.diff for с in цель.get("содержит", []))
        п["применяется"] = bool(з.проверка.get("применяется"))
    if вид in ("adr", "changelog"):
        новые = [ф for ф in з.изменены if fnmatch.fnmatch(ф, цель["новый"])]
        п["новый файл"] = bool(новые) and з.diff.count("new file mode") >= 1
        п["применяется"] = bool(з.проверка.get("применяется"))
        п["в черновике есть нужное"] = all(с in з.diff for с in цель.get("содержит", []))
        if вид == "adr":
            замечания = [з_ for ф in новые for з_ in (з.проверка.get("adr") or {}).get(ф, [])]
            п["ADR по шаблону"] = bool(новые) and not замечания
            п["замечания ADR"] = замечания
            sdd = з.проверка.get("sdd") or {}
            п["sdd.py без новых ошибок"] = (not sdd.get("есть")) or (
                sdd.get("ошибок_после") is not None and sdd["ошибок_после"] <= sdd.get("ошибок_до", 0))
        else:
            коммиты = копия.git("log", f"-{цель['коммитов']}", "--format=%h", з.база).split()
            названо = sum(1 for к in коммиты if к[:7] in з.diff)
            п["коммитов в разделе"] = f"{названо} из {len(коммиты)}"
            п["коммиты названы"] = названо >= цель["доля_коммитов"] * len(коммиты)
    if вид == "правила":
        файлы_случаев = {с["id"]: с["файл"] for с in все_случаи["случаи"]}
        посеяно = {файлы_случаев[и] for и in цель["нарушения"]}
        найдено = {н["файл"] for н in подтв} & посеяно
        ложные = [н for н in подтв if н.get("правило") in ПРАВИЛА_КОДА and н["файл"] not in set(файлы_случаев.values())
                  and н.get("роль") in ("нарушение", None, "")]
        п["найдено нарушений"] = f"{len(найдено)} из {len(посеяно)}"
        п["ключевые"] = sorted(найдено)
        п["нарушения найдены"] = len(найдено) >= цель["найти_не_меньше"]
        п["ложных"] = len(ложные)
        п["ложных в пределе"] = len(ложные) <= цель["ложных_не_больше"]
        if цель.get("правки"):
            п["правки нарушений"] = bool(посеяно & set(з.изменены)) and bool(з.проверка.get("применяется"))
    return п


def верно_кодом(п: dict[str, Any]) -> bool:
    return all(в for к, в in п.items() if isinstance(в, bool))


def судья(клиент: Any, цель: dict[str, Any], з: Any) -> tuple[bool, str]:
    находки = "; ".join(f"{н['файл']}:{н['строка']} «{str(н.get('строка_файла') or н.get('цитата', ''))[:120]}» — "
                        f"{str(н.get('суть', ''))[:80]}" for н in з.находки if н.get("подтверждена"))[:6000] or "—"
    текст = ПРОМПТ_СУДЬИ.format(цель=цель["цель"], итог=з.итог[:3000], находки=находки, diff=з.diff[:8000] or "—")
    for _ in range(3):
        try:
            r = клиент.call(СУДЬЯ, [{"role": "user", "content": текст}], max_tokens=300, temperature=0)
            д = json.loads(r.text[r.text.find("{"):r.text.rfind("}") + 1])
            return bool(д.get("верно")), str(д.get("почему") or "")[:240]
        except Exception:  # noqa: BLE001 — сеть или формат: повтор
            continue
    return False, "судья не ответил"


def прогнать(ассистент: Any, набор: dict[str, Any], клиент_судьи: Any, прогонов: int = 0, только: list[str] | None = None,
             ход: Any = print) -> list[dict[str, Any]]:
    копия = ассистент.копия
    копия.подготовить()
    все_случаи = случаи()
    ветка = копия.построить_случаи(все_случаи)
    итоги = []
    for номер in range(1, (прогонов or набор["критерий"]["прогонов"]) + 1):
        for ц in набор["цели"]:
            if только and ц["id"] not in только:
                continue
            база = ветка if ц["база"] == "случаи" else копия.база
            з = ассистент.выполнить(ц["цель"], база=база)
            п = проверить(ц, з, копия, все_случаи)
            код = верно_кодом(п)
            суд, почему = судья(клиент_судьи, ц, з) if з.статус != "не выполнено" else (False, "не выполнено")
            итог = {"цель": ц["id"], "вид": ц["вид"], "прогон": номер, "задача": з.id, "статус": з.статус,
                    "проверки": п, "код": код, "судья": суд, "почему": почему, "верно": код and суд,
                    "затронуты": sorted(затронуты(з, п)), "кругов": з.круги, "прочитано": len(з.прочитаны),
                    "секунд": з.секунд, "стоимость": round(з.стоимость, 4)}
            итоги.append(итог)
            плохие = [к for к, в in п.items() if в is False]
            ход(f"{ц['id']} #{номер} [{ц['вид']}] задача {з.id}: {'✓' if итог['верно'] else '✗'} "
                f"{', '.join(плохие)}{'' if суд else ' · судья: ' + почему} · кругов {з.круги}, "
                f"прочитано {len(з.прочитаны)}, {з.секунд} с, ${з.стоимость:.3f}"
                + (f" · полнота {п['полнота']}" if "полнота" in п else "")
                + (f" · {п['найдено нарушений']}, ложных {п['ложных']}" if "найдено нарушений" in п else ""))
    return итоги


def итог(итоги: list[dict[str, Any]], критерий: dict[str, Any]) -> dict[str, Any]:
    по_прогонам: dict[int, dict[str, int]] = {}
    for и in итоги:
        п = по_прогонам.setdefault(и["прогон"], {"верно": 0, "всего": 0})
        п["всего"] += 1
        п["верно"] += int(и["верно"])
    стабильность = []
    for ц in sorted({и["цель"] for и in итоги}):
        прогоны = [set(и["затронуты"]) for и in итоги if и["цель"] == ц]
        if len(прогоны) >= 2:
            а, б = прогоны[0], прогоны[1]
            стабильность.append((ц, round(len(а & б) / len(а | б), 2) if а | б else 1.0))
    стабильно = sum(1 for _, ж in стабильность if ж >= 0.8)
    выполнен = (all(п["верно"] >= критерий["верно_доля"] * п["всего"] for п in по_прогонам.values())
                and (not стабильность or стабильно >= критерий["стабильно_доля"] * len(стабильность)))
    секунды = sorted(и["секунд"] for и in итоги)
    return {"по_прогонам": по_прогонам, "стабильность": стабильность, "стабильно": f"{стабильно} из {len(стабильность)}",
            "критерий_выполнен": выполнен, "p50_с": секунды[len(секунды) // 2] if секунды else 0,
            "стоимость": round(sum(и["стоимость"] for и in итоги), 3),
            "неверные": [(и["цель"], и["прогон"], [к for к, в in и["проверки"].items() if в is False], и["почему"])
                         for и in итоги if not и["верно"]]}
