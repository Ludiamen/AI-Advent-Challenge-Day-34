class _Заглушка:
    def __init__(self, ответы: list[Any]) -> None:
        self.ответы, self.вызовы = list(ответы), []

    def call(self, модель, сообщения, **kw):
        self.вызовы.append({"сообщения": [dict(м) for м in сообщения], "инструменты": kw.get("tools")})
        о = self.ответы.pop(0)
        if isinstance(о, Exception):
            raise о
        return о


def _ответ(текст: str = "", вызовы: tuple = ()) -> Reply:
    тк = [ToolCall(f"c{i}", имя, арг) for i, (имя, арг) in enumerate(вызовы)]
    return Reply(текст, "ds-flash", prompt_tokens=100, completion_tokens=10, tool_calls=тк,
                 message={"role": "assistant", "content": текст,
                          **({"tool_calls": [{"id": в.ид, "type": "function", "function": {
                              "name": в.имя, "arguments": json.dumps(в.аргументы)}} for в in тк]} if тк else {})})


