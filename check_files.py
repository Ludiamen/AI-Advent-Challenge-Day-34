def часть_8(отчёт: Отчёт, с: Стенд) -> None:
    отчёт.часть(8, "Метрики без текстов")
    строки = metrics.прочитать(с.хр.метрики)
    задачи = [x for x in строки if x.get("событие") == "задача"]
    отчёт.пункт(bool(задачи), f"событий в журнале проверки: {len(строки)} (задач {len(задачи)})")
    отчёт.пункт(all(set(x) <= set(metrics.ПОЛЯ) for x in строки), "поля — только белый список")
    цели = [з.цель for з in с.хр.список(200)]
    текст = json.dumps(строки, ensure_ascii=False)
    отчёт.пункт(not any(ц[:30] in текст for ц in цели if len(ц) > 20), "целей и текстов в журнале нет")
    св = metrics.сводка(строки)
    отчёт(f"  задач {св['задач']} {св['итоги']}; p50 {св['p50_с']} с, p95 {св['p95_с']} с; кругов {св['кругов_в_среднем']}, "
          f"прочитано {св['прочитано_в_среднем']}; ${св['стоимость_на_задачу']} на задачу; применено {св['применено']}, "
          f"отклонено {св['отклонено']}")


def main() -> int:
    разбор = argparse.ArgumentParser(description="Проверка Дня 34: ассистент для работы с файлами проекта.")
    разбор.add_argument("--части", default="1,2,3,4,5,6,7,8")
    разбор.add_argument("--прогонов", type=int, default=0)
    разбор.add_argument("--заново", action="store_true", help="стереть память проверки (копию и задачи) перед прогоном")
    разбор.add_argument("--в", dest="out", default="")
    а = разбор.parse_args()
    части = {int(ч) for ч in а.части.split(",") if ч.strip()}
    if а.заново:
        shutil.rmtree(os.environ["MEMORY_DIR"], ignore_errors=True)
    os.makedirs(КАТАЛОГ, exist_ok=True)
    отчёт = Отчёт()
    начало = time.monotonic()
    отчёт(LINE)
    отчёт("Проверка Дня 34: ассистент для работы с файлами проекта")
    с = Стенд()
    шаги = [(1, lambda: часть_1(отчёт, с)), (2, lambda: часть_2(отчёт, с)), (3, lambda: часть_3(отчёт, с)),
            (4, lambda: часть_4(отчёт, с, а.прогонов)), (5, lambda: часть_5(отчёт, с)), (6, lambda: часть_6(отчёт, с)),
            (7, lambda: часть_7(отчёт, с)), (8, lambda: часть_8(отчёт, с))]
    if 1 not in части:
        с.снимок_до = workspace.снимок_оригинала(с.копия.оригинал)
        с.копия.подготовить()
    if 3 not in части and части & {5, 6}:
        с.ветка_случаев = с.копия.построить_случаи(evaluate.случаи())
    for номер, шаг in шаги:
        if номер in части:
            try:
                шаг()
            except (RuntimeError, OSError, ValueError, KeyError, LLMError) as exc:
                отчёт.пункт(False, f"часть {номер} прервана: {type(exc).__name__}: {exc}")
    отчёт(LINE)
    после = workspace.снимок_оригинала(с.копия.оригинал)
    отчёт.пункт(после == с.снимок_до, f"рабочая копия владельца не тронута: HEAD {после['HEAD'][:10]}, статус "
                f"{после['статус']} ({после['изменений']} изменений другой сессии) — как до прогона (NFR-02)")
    отчёт(f"ИТОГ: проверок {отчёт.проверок}, провалов {отчёт.провалов}. Прогон {_секунды(time.monotonic() - начало)}.")
    if а.out:
        with open(а.out, "a", encoding="utf-8") as f:
            f.write("\n```text\n" + "\n".join(отчёт.строки) + "\n```\n")
    return 1 if отчёт.провалов else 0


if __name__ == "__main__":
    sys.exit(main())
