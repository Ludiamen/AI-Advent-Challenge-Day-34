def _живая(с: Стенд, отчёт: Отчёт, ключ: str, цель: str) -> task.Задача:
    if ключ not in с.задачи:
        отчёт(f"  живая цель ({ключ}): «{цель}»")
        с.задачи[ключ] = с.ассистент().выполнить(цель, база=с.ветка_случаев or "cases/day34")
