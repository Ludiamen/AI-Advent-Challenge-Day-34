class _Окружение:
    """FILES_* на время проверки сервера: корень — копия, база, свой черновик."""

    def __init__(self, корень: str, база: str, черновик: str) -> None:
        self.новое = {"FILES_ROOT": корень, "FILES_BASE": база, "FILES_DRAFT": черновик}

    def __enter__(self):
        self.было = {к: os.environ.get(к) for к in self.новое}
        os.environ.update(self.новое)
        return self

    def __exit__(self, *_):
        for к, в in self.было.items():
            os.environ.pop(к, None) if в is None else os.environ.__setitem__(к, в)


